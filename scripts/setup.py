#!/usr/bin/env python3
"""Resolve, validate, and apply Doozo's local configuration.

This helper deliberately does not discover models or launch agents.  A host
workflow may pass its advertised capabilities with --capabilities-json; actual
route smoke tests belong to that host workflow.
"""

from __future__ import annotations

import argparse
import hashlib
import hmac
import json
import os
from pathlib import Path
import re
import sys
import tempfile
from dataclasses import dataclass
from typing import Any, Iterable, Optional, Tuple


SCRIPT_DIR = Path(__file__).resolve().parent
PLUGIN_DIR = SCRIPT_DIR.parent
DEFAULTS_PATH = PLUGIN_DIR / "defaults.json"

CONFIG_KEYS = {
    "schema_version",
    "preset",
    "max_workers",
    "model_fallback",
    "browser",
    "roles",
}
ROLE_NAMES = (
    "orchestrator",
    "scout",
    "implementer",
    "complex-implementer",
    "reviewer",
    "browser",
)
GENERATED_ROLE_NAMES = ROLE_NAMES[1:]
ADAPTIVE_ROLES = {"implementer", "complex-implementer"}
ADAPTIVE_EFFORTS = {"bounded": "medium", "complex": "high"}
ROLE_KEYS = {"model", "reasoning_effort"}
PRESETS = {"adaptive", "quality-first", "budget-first"}
BROWSER_DRIVERS = {"agent-browser", "cua", "playwright"}
REASONING_EFFORTS = {
    "none",
    "minimal",
    "low",
    "medium",
    "high",
    "xhigh",
    "max",
    "ultra",
}
GENERATED_HEADER = "# Generated by Doozo. Do not edit this file."
GENERATED_HASH_PREFIX = "# doozo-content-sha256: "
SHA256_RE = re.compile(r"^[0-9a-f]{64}$")


class SetupError(Exception):
    """An expected setup error that should be shown without a traceback."""


@dataclass(frozen=True)
class Paths:
    defaults: Path
    user_config: Path
    project_config: Path
    agents_dir: Path


@dataclass(frozen=True)
class Capabilities:
    models: dict[str, frozenset[str]]
    max_workers: Optional[int]
    source: str


@dataclass(frozen=True)
class State:
    paths: Paths
    defaults: dict[str, Any]
    user_config: dict[str, Any]
    user_exists: bool
    project_config: dict[str, Any]
    invocation: dict[str, Any]
    capabilities: Optional[Capabilities]


